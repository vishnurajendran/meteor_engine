// CodeEmitter.cs
// Pass 3: Generate .binding.h files for classes and enums using Sol2.

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace MeteorBindingGenerator;

public static class CodeEmitter
{
    private static HashSet<string> _boundClassNames = new();

    // ---- Class binding emission ---------------------------------------------

    public static string EmitClassBinding(BoundClass cls, string sourceIncludePath)
    {
        var sb = new StringBuilder();
        var guard = $"METEOR_BINDING_{cls.Name.ToUpper()}_H";

        sb.AppendLine($"// {cls.Name}.binding.h");
        sb.AppendLine($"// AUTO-GENERATED by MeteorBindingGenerator. DO NOT EDIT.");
        sb.AppendLine($"// Source: {Path.GetFileName(cls.SourceFile)}");
        sb.AppendLine();
        sb.AppendLine($"#ifndef {guard}");
        sb.AppendLine($"#define {guard}");
        sb.AppendLine();
        sb.AppendLine($"#include <sol/sol.hpp>");
        sb.AppendLine($"#include \"{sourceIncludePath}\"");
        sb.AppendLine();
        sb.AppendLine($"namespace MeteorBindings {{");
        sb.AppendLine();
        sb.AppendLine($"static void {cls.Name}_registerBinding(sol::state& lua) {{");

        var boundParents = cls.ParentClasses
            .Where(p => _boundClassNames.Contains(p))
            .ToList();

        bool hasMembers = cls.Properties.Count > 0 || cls.Functions.Count > 0;

        if (boundParents.Count == 0 && !hasMembers)
        {
            sb.AppendLine($"    lua.new_usertype<{cls.Name}>(\"{cls.Name}\");");
        }
        else
        {
            sb.AppendLine($"    lua.new_usertype<{cls.Name}>(\"{cls.Name}\",");

            var entries = new List<string>();

            if (boundParents.Count > 0)
            {
                var parentList = string.Join(", ", boundParents);
                entries.Add($"        sol::base_classes, sol::bases<{parentList}>()");

                // Type-casting constructor: ClassName(basePtr) does dynamic_cast.
                // Enables Python-like syntax in Lua:
                //   local derived = MDerived(self:find("./child"))
                // Accepts the first bound parent. dynamic_cast handles the full
                // inheritance chain regardless of how deep the hierarchy is.
                var castFrom = boundParents[0];
                entries.Add(
                    $"        sol::call_constructor, sol::factories(\n" +
                    $"            []({castFrom}* base) -> {cls.Name}* {{\n" +
                    $"                if (!base) return nullptr;\n" +
                    $"                return dynamic_cast<{cls.Name}*>(base);\n" +
                    $"            }}\n" +
                    $"        )");
            }

            foreach (var prop in cls.Properties)
                entries.Add(EmitProperty(cls, prop));

            foreach (var func in cls.Functions)
                entries.Add(EmitFunction(cls, func));

            for (int i = 0; i < entries.Count; i++)
            {
                var comma = (i < entries.Count - 1) ? "," : "";
                sb.AppendLine($"{entries[i]}{comma}");
            }

            sb.AppendLine($"    );");
        }

        sb.AppendLine($"}}");
        sb.AppendLine();
        sb.AppendLine($"}} // namespace MeteorBindings");
        sb.AppendLine();
        sb.AppendLine($"#endif // {guard}");

        return sb.ToString();
    }

    // ---- Enum binding emission ----------------------------------------------

    public static string EmitEnumBinding(BoundEnum boundEnum, string sourceIncludePath)
    {
        var sb = new StringBuilder();
        var guard = $"METEOR_BINDING_ENUM_{boundEnum.Name.ToUpper()}_H";

        sb.AppendLine($"// {boundEnum.Name}.binding.h");
        sb.AppendLine($"// AUTO-GENERATED by MeteorBindingGenerator. DO NOT EDIT.");
        sb.AppendLine($"// Source: {Path.GetFileName(boundEnum.SourceFile)}");
        sb.AppendLine();
        sb.AppendLine($"#ifndef {guard}");
        sb.AppendLine($"#define {guard}");
        sb.AppendLine();
        sb.AppendLine($"#include <sol/sol.hpp>");
        sb.AppendLine($"#include \"{sourceIncludePath}\"");
        sb.AppendLine();
        sb.AppendLine($"namespace MeteorBindings {{");
        sb.AppendLine();
        sb.AppendLine($"static void {boundEnum.Name}_registerBinding(sol::state& lua) {{");

        var qualifier = boundEnum.Name + "::";

        sb.AppendLine($"    lua.new_enum<{boundEnum.Name}>(\"{boundEnum.Name}\",");
        sb.AppendLine($"        {{");

        for (int i = 0; i < boundEnum.Values.Count; i++)
        {
            var val = boundEnum.Values[i];
            var comma = (i < boundEnum.Values.Count - 1) ? "," : "";
            sb.AppendLine($"            {{\"{val}\", {qualifier}{val}}}{comma}");
        }

        sb.AppendLine($"        }}");
        sb.AppendLine($"    );");

        sb.AppendLine($"}}");
        sb.AppendLine();
        sb.AppendLine($"}} // namespace MeteorBindings");
        sb.AppendLine();
        sb.AppendLine($"#endif // {guard}");

        return sb.ToString();
    }

    // ---- Batch emission -----------------------------------------------------

    public static List<string> EmitAll(List<BoundClass> boundClasses, List<BoundEnum> boundEnums,
                                        string outputDir, string sourceDir)
    {
        Directory.CreateDirectory(outputDir);
        var generatedFiles = new List<string>();

        _boundClassNames = new HashSet<string>(boundClasses.Select(c => c.Name));

        var normalizedSourceDir = Path.GetFullPath(sourceDir)
            .TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);

        foreach (var boundEnum in boundEnums)
        {
            var fullPath = Path.GetFullPath(boundEnum.SourceFile);
            var relativePath = Path.GetRelativePath(normalizedSourceDir, fullPath)
                                   .Replace('\\', '/');

            var content = EmitEnumBinding(boundEnum, relativePath);
            var fileName = $"{boundEnum.Name}.binding.h";
            var filePath = Path.Combine(outputDir, fileName);
            File.WriteAllText(filePath, content);
            generatedFiles.Add(filePath);
            Console.WriteLine($"  Generated: {fileName} (enum, {boundEnum.Values.Count} values)");
        }

        foreach (var cls in boundClasses)
        {
            var fullPath = Path.GetFullPath(cls.SourceFile);
            var relativePath = Path.GetRelativePath(normalizedSourceDir, fullPath)
                                   .Replace('\\', '/');

            var content = EmitClassBinding(cls, relativePath);
            var fileName = $"{cls.Name}.binding.h";
            var filePath = Path.Combine(outputDir, fileName);
            File.WriteAllText(filePath, content);
            generatedFiles.Add(filePath);

            var boundParents = cls.ParentClasses.Where(p => _boundClassNames.Contains(p)).ToList();
            var parentInfo = boundParents.Count > 0
                ? $" -> [{string.Join(", ", boundParents)}]"
                : "";
            Console.WriteLine($"  Generated: {fileName}{parentInfo}");
        }

        return generatedFiles;
    }

    // ---- Property emission --------------------------------------------------

    private static string EmitProperty(BoundClass cls, BoundProperty prop)
    {
        return prop.AccessKind switch
        {
            PropertyAccessKind.Direct =>
                $"        \"{prop.Name}\", &{cls.Name}::{prop.Name}",

            PropertyAccessKind.DeclareField =>
                $"        \"{prop.Name}\", sol::property(\n" +
                $"            [](const {cls.Name}& self) -> {prop.CppType} {{ return self.{prop.Name}.get(); }},\n" +
                $"            []({cls.Name}& self, const {prop.CppType}& v) {{ self.{prop.Name}.set(v); }}\n" +
                $"        )",

            PropertyAccessKind.RefProp =>
                $"        \"{prop.Name}\", sol::property(\n" +
                $"            [](const {cls.Name}& self) -> {prop.CppType}* {{ return self.{prop.Name}.get(); }}\n" +
                $"        )",

            _ => $"        // TODO: unknown access kind for '{prop.Name}'"
        };
    }

    // ---- Function emission --------------------------------------------------

    private static string EmitFunction(BoundClass cls, BoundFunction func)
    {
        if (NeedsWrapper(func))
            return EmitWrappedFunction(cls, func);

        return $"        \"{func.Name}\", &{cls.Name}::{func.Name}";
    }

    // TAssetHandle<T> / TAssetRef<T>. Group 1 = template, group 2 = T.
    private static readonly Regex AssetTypePattern =
        new(@"\b(TAssetHandle|TAssetRef)\s*<\s*(\w+)\s*>", RegexOptions.Compiled);

    /// <summary>True for TAssetHandle&lt;T&gt; and TAssetRef&lt;T&gt; (any qualifiers).</summary>
    public static bool IsAssetType(string cppType) => AssetTypePattern.IsMatch(cppType);

    /// <summary>
    /// Functions whose signature can't cross into Lua as-is get a lambda
    /// wrapper that converts at the boundary:
    ///   - std::vector returns  -> copied into a plain Lua table
    ///   - asset handle/ref params and returns -> Lua's single MAssetHandle type
    /// </summary>
    private static bool NeedsWrapper(BoundFunction func) =>
        ReturnsVector(func)
        || IsAssetType(func.DeclaredReturnType)
        || func.DeclaredParameters.Any(p => IsAssetType(p.Type));

    /// <summary>True when the function returns a std::vector (by value or reference).</summary>
    public static bool ReturnsVector(BoundFunction func)
    {
        return func.DeclaredReturnType.Contains("vector<") || func.ReturnType.Contains("vector<");
    }

    /// <summary>
    /// Emits a lambda that calls the function and converts at the boundary.
    ///
    /// std::vector returns: Lua gets a COPY as a plain 1-based table. Binding
    /// &amp;Class::func directly would hand out a returned reference as the
    /// engine's live container (scripts could add and remove entries behind
    /// its back), and a returned value as container userdata, which
    /// table.insert / table.sort / type() don't treat as a table.
    ///
    /// Assets: Lua has one handle type, MAssetHandle = TAssetHandle&lt;MAsset&gt;
    /// (asset_bindings.h). Parameters accept it and narrow it to the declared
    /// TAssetHandle&lt;T&gt; / TAssetRef&lt;T&gt;; returns widen back to
    /// MAssetHandle. Both go through strictAssetCast (asset_handle.h), so a
    /// handle to another asset type becomes a null handle, both ways.
    ///
    /// Calling through a lambda also sidesteps overload ambiguity, since the
    /// member function's address is never taken.
    /// </summary>
    private static string EmitWrappedFunction(BoundClass cls, BoundFunction func)
    {
        var signature = new List<string>();
        if (!func.IsStatic)
            signature.Add($"{cls.Name}& self");

        // As written in the header - the AST pass may have simplified them.
        var args = new List<string>();
        foreach (var (type, name) in func.DeclaredParameters)
        {
            var asset = AssetTypePattern.Match(type);
            if (!asset.Success)
            {
                signature.Add($"{type} {name}");
                args.Add(name);
                continue;
            }

            signature.Add($"const TAssetHandle<MAsset>& {name}");
            var typedHandle = $"strictAssetCast<{asset.Groups[2].Value}>({name})";
            args.Add(asset.Groups[1].Value == "TAssetRef"
                ? $"TAssetRef<{asset.Groups[2].Value}>({typedHandle})"
                : typedHandle);
        }

        var target = func.IsStatic ? $"{cls.Name}::{func.Name}" : $"self.{func.Name}";
        var call = $"{target}({string.Join(", ", args)})";
        var lambda = $"[]({string.Join(", ", signature)})";

        string body;
        var returnAsset = AssetTypePattern.Match(func.DeclaredReturnType);
        if (ReturnsVector(func))
        {
            body =
                $"            auto items = {call}; // copy - Lua never holds the engine's container\n" +
                $"            return sol::as_table(std::move(items));\n";
        }
        else if (returnAsset.Success)
        {
            // Checked against the declared type before widening, so a wrong-type
            // GUID stored in the engine comes back as a null handle.
            var assetType = returnAsset.Groups[2].Value;
            var handleExpr = returnAsset.Groups[1].Value == "TAssetRef" ? $"{call}.getHandle()" : call;
            body = $"            return TAssetHandle<MAsset>(strictAssetCast<{assetType}>({handleExpr}));\n";
        }
        else if (func.DeclaredReturnType.Trim() == "void")
        {
            body = $"            {call};\n";
        }
        else
        {
            // Pass the result through untouched (references stay references).
            lambda += " -> decltype(auto)";
            body = $"            return {call};\n";
        }

        return
            $"        \"{func.Name}\", {lambda} {{\n" +
            body +
            $"        }}";
    }
}